import assert from 'node:assert/strict';
import { after, before, describe, test } from 'node:test';
import { addMember, Session, setupWorkspace, startApp, type Json, type TestApp } from './helpers.ts';
import { asBot, botOk, createPlatformApp, sleep, SocketApp, type TestAppCredentials } from './platform-helpers.ts';

process.env.EVENT_ACK_TIMEOUT_MS = '250';
process.env.STREAM_TIMEOUT_MS = '700';
process.env.STATUS_TIMEOUT_MS = '300';

describe('agent surfaces: streamed messages and thread status', () => {
  let t: TestApp;
  let owner: Session;
  let member: Session;
  let general: string;
  let agent: TestAppCredentials;

  before(async () => {
    t = await startApp();
    owner = await setupWorkspace(t);
    member = await addMember(t, owner, 'Mina Member');
    general = (await owner.ok('client.boot')).channels.find((channel: Json) => channel.is_general).id;
    agent = await createPlatformApp(owner, 'Atlas');
    await owner.ok('conversations.invite', { channel: general, users: agent.botUserId });
  });
  after(() => t.close());

  const ask = async (text: string): Promise<string> => (await member.ok('chat.postMessage', { channel: general, text })).ts;
  const read = async (ts: string): Promise<Json> =>
    (await owner.ok('conversations.replies', { channel: general, ts })).messages.at(-1);

  test('a streamed answer is one message that grows, then settles', async () => {
    const question = await ask('Why did the build fail?');
    const stream = await member.connect();
    const socket = await SocketApp.connect(t.base, agent.appToken);

    const started = await botOk(t.base, agent, 'chat.startStream', {
      channel: general,
      thread_ts: question,
      recipient_user_id: member.userId,
      recipient_team_id: 'T0',
    });
    assert.deepEqual(Object.keys(started).sort(), ['channel', 'ok', 'ts']);
    const first = await stream.next((event) => event.type === 'message' && event.ts === started.ts);
    assert.equal(first.streaming, true);
    assert.equal(first.thread_ts, question);
    assert.equal(first.bot_id, agent.botId);

    const words = 'The tax helper rounds half up since yesterday. One fixture lands on a half cent.'.split(' ');
    for (const word of words) {
      const appended = await botOk(t.base, agent, 'chat.appendStream', { channel: general, ts: started.ts, markdown_text: `${word} ` });
      assert.deepEqual(appended, { ok: true, channel: general, ts: started.ts });
      await sleep(30); // a token every 30 ms, faster than clients are updated
    }
    const during = await read(question);
    assert.equal(during.streaming, true);

    const stopped = await botOk(t.base, agent, 'chat.stopStream', {
      channel: general,
      ts: started.ts,
      markdown_text: '**Fixed in #418.**',
      blocks: [{ type: 'context', elements: [{ type: 'mrkdwn', text: 'Generated by Atlas' }] }],
    });
    const full = `${words.join(' ')} **Fixed in #418.**`;
    assert.equal(stopped.message.text, full);
    assert.equal(stopped.message.streaming, undefined);
    assert.deepEqual(stopped.message.blocks, [
      { type: 'markdown', text: full },
      { type: 'context', elements: [{ type: 'mrkdwn', text: 'Generated by Atlas' }] },
    ]);
    // A streamed message is not an edited message.
    assert.equal(stopped.message.edited, undefined);
    assert.deepEqual(await read(question), { ...stopped.message });

    // Clients saw it change, but far fewer times than it was appended to.
    const final = await stream.next((event) => event.subtype === 'message_changed' && event.message.ts === started.ts && !event.message.streaming);
    assert.equal(final.message.text, full);
    const changes = stream.events.filter((event) => event.subtype === 'message_changed' && event.message.ts === started.ts);
    assert.ok(changes.length >= 3 && changes.length <= 7, `saw ${changes.length} updates for ${words.length} appends`);
    assert.ok(changes.slice(0, -1).every((event) => event.message.streaming === true));

    // Apps (here the agent itself) see the message appear and its final form, not every step.
    await socket.event('message', (event) => event.subtype === 'message_changed' && event.message.ts === started.ts);
    await sleep(50);
    assert.equal(socket.events('message').filter((event) => event.message?.ts === started.ts).length, 1);
    assert.equal(socket.events('message').filter((event) => event.ts === started.ts).length, 1);

    // The text is searchable like any other message.
    assert.equal((await owner.ok('search.messages', { query: 'fixture lands' })).messages.total, 1);
    stream.close();
    socket.close();
  });

  test('stream errors use Slack’s codes', async () => {
    const question = await ask('Another question');
    const { ts } = await botOk(t.base, agent, 'chat.startStream', { channel: general, thread_ts: question, markdown_text: 'Start. ' });
    const call = (method: string, args: Json, as = agent): Promise<Json> => asBot(t.base, as, method, { channel: general, ts, ...args });

    assert.equal((await call('chat.appendStream', {})).error, 'markdown_text_or_chunks_required');
    assert.equal((await call('chat.appendStream', { markdown_text: 'a', chunks: [{ type: 'markdown_text', text: 'b' }] })).error, 'cannot_provide_both_markdown_text_and_chunks');
    assert.equal((await call('chat.appendStream', { chunks: [{ type: 'markdown_text', text: 'b' }] })).error, 'streaming_mode_mismatch');
    assert.equal((await call('chat.appendStream', { markdown_text: 'x'.repeat(12_000) })).error, 'msg_too_long');

    const other = await createPlatformApp(owner, 'Other Agent');
    await owner.ok('conversations.invite', { channel: general, users: other.botUserId });
    assert.equal((await call('chat.appendStream', { markdown_text: 'mine now' }, other)).error, 'message_not_owned_by_app');
    assert.equal((await call('chat.stopStream', {}, other)).error, 'message_not_owned_by_app');

    assert.equal((await call('chat.stopStream', {})).message.text, 'Start. ');
    assert.equal((await call('chat.appendStream', { markdown_text: 'late' })).error, 'message_not_in_streaming_state');
    assert.equal((await call('chat.stopStream', {})).error, 'message_not_in_streaming_state');
    assert.equal((await asBot(t.base, agent, 'chat.appendStream', { channel: general, ts: '1000000000.000001', markdown_text: 'x' })).error, 'message_not_found');
    assert.equal((await asBot(t.base, agent, 'chat.startStream', { channel: general, thread_ts: '1000000000.000001' })).error, 'invalid_thread_ts');
    assert.equal((await asBot(t.base, agent, 'chat.startStream', { channel: 'C0NOTHERE00' })).error, 'channel_not_found');
  });

  test('chunks carry text, task progress and blocks the way the SDK stream helper sends them', async () => {
    const question = await ask('Plan the release');
    const { ts } = await botOk(t.base, agent, 'chat.startStream', {
      channel: general,
      thread_ts: question,
      task_display_mode: 'plan',
      chunks: [
        { type: 'plan_update', title: 'Release plan' },
        { type: 'task_update', id: 'tests', title: 'Run the test suite', status: 'in_progress' },
        { type: 'task_update', id: 'notes', title: 'Write release notes', status: 'pending' },
      ],
    });
    await botOk(t.base, agent, 'chat.appendStream', {
      channel: general,
      ts,
      chunks: [
        { type: 'markdown_text', text: 'Working through ' },
        { type: 'markdown_text', text: 'the checklist.' },
        { type: 'task_update', id: 'tests', status: 'complete', output: '1,205 passed', sources: [{ type: 'url', url: 'https://ci.example.com/1482', text: 'CI run' }] },
      ],
    });
    // The helper always ends with a chunks array, possibly an empty one.
    const stopped = await botOk(t.base, agent, 'chat.stopStream', {
      channel: general,
      ts,
      chunks: [{ type: 'blocks', blocks: [{ type: 'divider', block_id: 'end' }] }],
    });
    assert.equal(stopped.message.text, 'Working through the checklist.');
    assert.deepEqual(stopped.message.blocks, [
      { type: 'markdown', text: 'Working through the checklist.' },
      {
        type: 'plan',
        title: 'Release plan',
        tasks: [
          {
            task_id: 'tests',
            title: 'Run the test suite',
            status: 'complete',
            output: { type: 'rich_text', elements: [{ type: 'rich_text_section', elements: [{ type: 'text', text: '1,205 passed' }] }] },
            sources: [{ type: 'url', url: 'https://ci.example.com/1482', text: 'CI run' }],
          },
          { task_id: 'notes', title: 'Write release notes', status: 'pending' },
        ],
      },
      { type: 'divider', block_id: 'end' },
    ]);

    const empty = await botOk(t.base, agent, 'chat.startStream', { channel: general, thread_ts: question });
    assert.equal((await asBot(t.base, agent, 'chat.stopStream', { channel: general, ts: empty.ts, chunks: [] })).ok, true);
    assert.equal((await asBot(t.base, agent, 'chat.appendStream', { channel: general, ts, chunks: [{ type: 'mystery' }] })).error, 'message_not_in_streaming_state');
    const bad = await botOk(t.base, agent, 'chat.startStream', { channel: general, thread_ts: question });
    assert.equal((await asBot(t.base, agent, 'chat.appendStream', { channel: general, ts: bad.ts, chunks: [{ type: 'mystery' }] })).error, 'invalid_chunks');
  });

  test('a stream the app never stops is finalised on its own', async () => {
    const question = await ask('Slow question');
    const { ts } = await botOk(t.base, agent, 'chat.startStream', {
      channel: general,
      thread_ts: question,
      chunks: [
        { type: 'markdown_text', text: 'Half an answer' },
        { type: 'task_update', id: 'dig', title: 'Digging', status: 'in_progress' },
      ],
    });
    assert.equal((await read(question)).streaming, true);
    await sleep(900);
    const settled = await read(question);
    assert.equal(settled.ts, ts);
    assert.equal(settled.streaming, undefined);
    assert.equal(settled.text, 'Half an answer');
    assert.equal(settled.blocks[1].status, 'error');
    assert.equal((await asBot(t.base, agent, 'chat.stopStream', { channel: general, ts })).error, 'message_not_in_streaming_state');
  });

  test('a thread status shows while the agent works and clears when it answers', async () => {
    const question = await ask('Thinking test');
    const stream = await member.connect();
    assert.deepEqual(
      await asBot(t.base, agent, 'assistant.threads.setStatus', {
        channel_id: general,
        thread_ts: question,
        status: 'is reading the build log…',
        loading_messages: ['Reading logs', 'Comparing commits'],
      }),
      { ok: true },
    );
    const shown = await stream.next((event) => event.type === 'assistant_thread_status');
    assert.deepEqual(shown, {
      type: 'assistant_thread_status',
      channel: general,
      thread_ts: question,
      user: agent.botUserId,
      status: 'is reading the build log…',
      loading_messages: ['Reading logs', 'Comparing commits'],
    });

    await botOk(t.base, agent, 'chat.postMessage', { channel: general, thread_ts: question, text: 'Found it.' });
    const cleared = await stream.next((event) => event.type === 'assistant_thread_status' && event.status === '');
    assert.equal(cleared.thread_ts, question);

    // Left alone, a status expires; an explicit empty status clears it too.
    await botOk(t.base, agent, 'assistant.threads.setStatus', { channel_id: general, thread_ts: question, status: 'is still thinking…' });
    await sleep(450);
    assert.equal(stream.events.filter((event) => event.type === 'assistant_thread_status' && event.status === '').length, 2);
    await botOk(t.base, agent, 'assistant.threads.setStatus', { channel_id: general, thread_ts: question, status: 'again' });
    await botOk(t.base, agent, 'assistant.threads.setStatus', { channel_id: general, thread_ts: question, status: '' });
    await sleep(50);
    assert.equal(stream.events.filter((event) => event.type === 'assistant_thread_status' && event.status === '').length, 3);

    const missing = await asBot(t.base, agent, 'assistant.threads.setStatus', { channel_id: general, thread_ts: '1000000000.000001', status: 'x' });
    assert.deepEqual(missing, { ok: false, error: 'invalid_thread_ts', detail: 'Thread not found' });

    await botOk(t.base, agent, 'assistant.threads.setTitle', { channel_id: general, thread_ts: question, title: 'Build failure' });
    const title = await stream.next((event) => event.type === 'assistant_thread_title');
    assert.equal(title.title, 'Build failure');
    await botOk(t.base, agent, 'assistant.threads.setSuggestedPrompts', {
      channel_id: general,
      thread_ts: question,
      title: 'Try asking',
      prompts: [{ title: 'Summarise', message: 'Summarise this thread' }],
    });
    const prompts = await stream.next((event) => event.type === 'assistant_thread_prompts');
    assert.deepEqual(prompts.prompts, [{ title: 'Summarise', message: 'Summarise this thread' }]);
    stream.close();
  });

  test('calls to methods that do not exist are counted for the admin', async () => {
    assert.equal((await asBot(t.base, agent, 'workflows.stepCompleted', { function_execution_id: 'x' })).error, 'unknown_method');
    assert.equal((await asBot(t.base, agent, 'workflows.stepCompleted', { function_execution_id: 'x' })).error, 'unknown_method');
    assert.equal((await asBot(t.base, agent, 'canvases.create')).error, 'unknown_method');
    await fetch(`${t.base}/api/${'x'.repeat(300)}`, { method: 'POST' });
    assert.equal((await member.call('client.apps.unknownMethods')).error, 'not_allowed');
    const { methods } = await owner.ok('client.apps.unknownMethods');
    assert.deepEqual(
      methods.map((entry: Json) => [entry.name, entry.calls]),
      [
        ['workflows.stepCompleted', 2],
        ['canvases.create', 1],
      ],
    );
    assert.ok(methods[0].last_seen >= methods[0].first_seen);
  });
});
